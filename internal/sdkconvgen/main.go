// sdkconvgen generates the registry of sdk-go oneof wrapper types used by
// libs/sdktypes/sdkconv.
//
// sdk-go models a oneof as an unexported interface field holding a pointer to
// a wrapper struct (Parent_Field_Alt). Reflection cannot enumerate the types
// implementing an interface, so sdkconv needs this list to convert JSON
// mirrors (flattened oneofs) back into sdk-go types.
//
// Usage: go run ./internal/sdkconvgen <out file> <sdk package>...
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	if len(os.Args) < 3 {
		fmt.Fprintln(os.Stderr, "usage: sdkconvgen <out file> <sdk package>...")
		os.Exit(2)
	}
	pkgs := os.Args[2:]
	slices.Sort(pkgs)

	var imports, entries bytes.Buffer
	for _, pkg := range pkgs {
		names, err := wrappers(pkg)
		if err != nil {
			fmt.Fprintf(os.Stderr, "%s: %v\n", pkg, err)
			os.Exit(1)
		}
		if len(names) == 0 {
			continue
		}
		alias := strings.NewReplacer("/", "", "-", "").Replace(strings.TrimPrefix(pkg, "github.com/databricks/sdk-go/"))
		fmt.Fprintf(&imports, "\t%s %q\n", alias, pkg)
		for _, n := range names {
			fmt.Fprintf(&entries, "\t(*%s.%s)(nil),\n", alias, n)
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/sdkconvgen. DO NOT EDIT.\n\npackage sdkconv\n\nimport (\n")
	buf.Write(imports.Bytes())
	buf.WriteString(")\n\n// oneofWrappers lists the oneof wrapper types of every sdk-go package.\nvar oneofWrappers = []any{\n")
	buf.Write(entries.Bytes())
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[1], src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// wrappers returns the names of types with a `func (*T) isX()` marker method.
func wrappers(pkg string) ([]string, error) {
	out, err := exec.Command("go", "list", "-f", "{{.Dir}}", pkg).Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(strings.TrimSpace(string(out)), "model.go"), nil, 0)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Recv == nil || !strings.HasPrefix(fd.Name.Name, "is") || fd.Type.Params.NumFields() != 0 {
			continue
		}
		star, ok := fd.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		if id, ok := star.X.(*ast.Ident); ok && id.IsExported() {
			names = append(names, id.Name)
		}
	}
	slices.Sort(names)
	return names, nil
}
