"""
Generates the per-resource wiring in databricks.bundles.core that used to be
hand-written: the _ResourceType registry, the Resources add_*/property methods,
the *_mutator decorators, and the core package __init__.

Everything specific to a resource type is emitted here so that adding a resource
needs no manual edits under databricks/bundles/core. The static, non-resource
parts of core stay hand-written (see _CORE_INIT_STATIC_EXPORTS / _CORE_INIT_STATIC_IMPORTS).
"""

from dataclasses import dataclass
from pathlib import Path

import codegen.packages as packages

HEADER = "# Code generated by pydabs-codegen. DO NOT EDIT.\n\n"


@dataclass(frozen=True)
class _WiredResource:
    class_name: str
    """Resource dataclass name, e.g. "Job"."""

    singular_name: str
    """Singular name used in methods and messages, e.g. "job"."""

    plural_name: str
    """Plural name, the same as the "resources" bundle section, e.g. "jobs"."""

    model_module: str
    """Module the resource dataclass lives in, e.g. "databricks.bundles.jobs._models.job"."""


def _wired_resources() -> list[_WiredResource]:
    # Every namespaced resource is wired. RESOURCE_NAMESPACE is the single source
    # of truth for both model generation and wiring.
    resources = []

    for ref, namespace in packages.RESOURCE_NAMESPACE.items():
        class_name = packages.get_class_name(ref)

        resources.append(
            _WiredResource(
                class_name=class_name,
                singular_name=class_name.lower(),
                plural_name=namespace,
                model_module=packages.get_package(namespace, ref),
            )
        )

    resources.sort(key=lambda r: r.plural_name)

    return resources


def write_wiring(output: str):
    resources = _wired_resources()

    core_path = Path(output) / "databricks" / "bundles" / "core"
    generated_path = core_path / "_generated"
    generated_path.mkdir(parents=True, exist_ok=True)

    (generated_path / "__init__.py").write_text(HEADER.rstrip() + "\n")
    (generated_path / "_resource_types.py").write_text(
        HEADER + _resource_types_code(resources)
    )
    (generated_path / "_resources.py").write_text(HEADER + _resources_code(resources))
    (generated_path / "_resource_mutators.py").write_text(
        HEADER + _resource_mutators_code(resources)
    )
    (core_path / "__init__.py").write_text(HEADER + _core_init_code(resources))

    print(f"Writing wiring into {generated_path}")


def _resource_types_code(resources: list[_WiredResource]) -> str:
    model_imports = "\n".join(
        f"    from {r.model_module} import {r.class_name}" for r in resources
    )

    entries = "\n".join(
        f"""        _ResourceType(
            resource_type={r.class_name},
            singular_name="{r.singular_name}",
            plural_name="{r.plural_name}",
        ),"""
        for r in resources
    )

    return f"""from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from databricks.bundles.core._resource_type import _ResourceType


def _all_resource_types() -> "tuple[_ResourceType, ...]":
    # Lazily import resource types so that databricks.bundles.core is not
    # imported from databricks.bundles.<resource_type>.
    from databricks.bundles.core._resource_type import _ResourceType

{model_imports}

    return (
{entries}
    )
"""


def _resources_code(resources: list[_WiredResource]) -> str:
    type_checking_imports = "\n".join(
        f"    from {r.model_module} import {r.class_name}, {r.class_name}Param"
        for r in resources
    )

    properties = "\n\n".join(
        f'''    @property
    def {r.plural_name}(self) -> dict[str, "{r.class_name}"]:
        return self._resources["{r.plural_name}"]'''
        for r in resources
    )

    methods = "\n\n".join(_add_method_code(r) for r in resources)

    return f'''from typing import TYPE_CHECKING, Optional

from databricks.bundles.core._location import Location
from databricks.bundles.core._transform import _transform

if TYPE_CHECKING:
{type_checking_imports}

__all__ = ["_GeneratedResources"]


class _GeneratedResources:
    """
    Generated per-resource accessors and add_* methods, mixed into Resources.
    """

    # Provided by the Resources subclass; declared here so the generated methods
    # below type-check.
    _resources: dict[str, dict]

    if TYPE_CHECKING:

        def add_location(
            self, path: tuple[str, ...], location: Location
        ) -> None: ...

        def add_diagnostic_error(
            self,
            msg: str,
            *,
            detail: Optional[str] = None,
            path: Optional[tuple[str, ...]] = None,
            location: Optional[Location] = None,
        ) -> None: ...

{properties}

{methods}
'''


def _add_method_code(r: _WiredResource) -> str:
    return f'''    def add_{r.singular_name}(
        self,
        resource_name: str,
        {r.singular_name}: "{r.class_name}Param",
        *,
        location: Optional[Location] = None,
    ) -> None:
        """
        Adds {_article(r.singular_name)} {r.singular_name} to the collection of resources. Resource name must be unique across all {r.plural_name}.

        :param resource_name: unique identifier for the {r.singular_name}
        :param {r.singular_name}: the {r.singular_name} to add, can be {r.class_name} or dict
        :param location: optional location of the {r.singular_name} in the source code
        """
        from {r.model_module} import {r.class_name}

        {r.singular_name} = _transform({r.class_name}, {r.singular_name})
        path = ("resources", "{r.plural_name}", resource_name)
        location = location or Location.from_stack_frame(depth=1)

        if self._resources["{r.plural_name}"].get(resource_name):
            self.add_diagnostic_error(
                msg=f"Duplicate resource name '{{resource_name}}' for resource '{r.singular_name}'. Resource names must be unique.",
                location=location,
                path=path,
            )
        else:
            if location:
                self.add_location(path, location)

            self._resources["{r.plural_name}"][resource_name] = {r.singular_name}'''


def _resource_mutators_code(resources: list[_WiredResource]) -> str:
    type_checking_imports = "\n".join(
        f"    from {r.model_module} import {r.class_name}" for r in resources
    )

    exports = ", ".join(f'"{r.singular_name}_mutator"' for r in resources)

    decorators = "\n\n\n".join(_mutator_code(r) for r in resources)

    return f"""from collections.abc import Callable
from typing import TYPE_CHECKING, overload

from databricks.bundles.core._bundle import Bundle
from databricks.bundles.core._resource_mutator import ResourceMutator

if TYPE_CHECKING:
{type_checking_imports}

__all__ = [{exports}]


{decorators}
"""


def _mutator_code(r: _WiredResource) -> str:
    name = f"{r.singular_name}_mutator"

    return f'''@overload
def {name}(
    function: Callable[[Bundle, "{r.class_name}"], "{r.class_name}"],
) -> ResourceMutator["{r.class_name}"]: ...


@overload
def {name}(
    function: Callable[["{r.class_name}"], "{r.class_name}"],
) -> ResourceMutator["{r.class_name}"]: ...


def {name}(function: Callable) -> ResourceMutator["{r.class_name}"]:
    """
    Decorator for defining {_article(r.singular_name)} {r.singular_name} mutator. Function should return a new instance of the {r.singular_name}
    with the desired changes, instead of mutating the input {r.singular_name}.

    Example:

    .. code-block:: python

        @{name}
        def my_{name}(bundle: Bundle, {r.singular_name}: {r.class_name}) -> {r.class_name}:
            return replace({r.singular_name}, ...)

    :param function: Function that mutates {_article(r.singular_name)} {r.singular_name}.
    """
    from {r.model_module} import {r.class_name}

    return ResourceMutator(resource_type={r.class_name}, function=function)'''


# Static, non-resource exports of databricks.bundles.core. Kept here because the
# package __init__ is generated; the resource mutators are appended and the whole
# list is sorted.
_CORE_INIT_STATIC_EXPORTS = [
    "Bundle",
    "Diagnostic",
    "Diagnostics",
    "Location",
    "Resource",
    "ResourceMutator",
    "Resources",
    "Severity",
    "Variable",
    "VariableOr",
    "VariableOrDict",
    "VariableOrList",
    "VariableOrOptional",
    "load_resources_from_current_package_module",
    "load_resources_from_module",
    "load_resources_from_modules",
    "load_resources_from_package_module",
    "variables",
]

_CORE_INIT_STATIC_IMPORTS = """from databricks.bundles.core._bundle import Bundle
from databricks.bundles.core._diagnostics import (
    Diagnostic,
    Diagnostics,
    Severity,
)
from databricks.bundles.core._load import (
    load_resources_from_current_package_module,
    load_resources_from_module,
    load_resources_from_modules,
    load_resources_from_package_module,
)
from databricks.bundles.core._location import Location
from databricks.bundles.core._resource import Resource
from databricks.bundles.core._resource_mutator import ResourceMutator
from databricks.bundles.core._resources import Resources
from databricks.bundles.core._variable import (
    Variable,
    VariableOr,
    VariableOrDict,
    VariableOrList,
    VariableOrOptional,
    variables,
)"""


def _core_init_code(resources: list[_WiredResource]) -> str:
    mutator_names = [f"{r.singular_name}_mutator" for r in resources]

    all_exports = sorted(_CORE_INIT_STATIC_EXPORTS + mutator_names)
    all_block = "\n".join(f'    "{name}",' for name in all_exports)

    mutator_imports = ",\n".join(f"    {name}" for name in sorted(mutator_names))

    return f"""__all__ = [
{all_block}
]

{_CORE_INIT_STATIC_IMPORTS}
from databricks.bundles.core._generated._resource_mutators import (
{mutator_imports},
)
"""
