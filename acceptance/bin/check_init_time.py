#!/usr/bin/env python3
"""
Fail if any Go package's init() clock time, per GODEBUG=inittrace=1, exceeds a threshold,
and keep a golden file with an upper bound on each package's init time.

Each package is judged by its minimum over several runs, since load from parallel tests
inflates individual runs but a slow init is slow on every run. Load comes in bursts that
span consecutive runs, so packages over a limit get more runs (up to --max-runs).

The golden file lists packages with a non-trivial init and their tolerated maximum; any
other package's maximum is MIN_LIMIT_MS. A recorded maximum is kept as long as the package
stays under it, so the file only changes when a package becomes several times slower (or
disappears). In that case the maximum is raised to TOLERANCE times the new measurement and
the diff shows up for review. Delete the file and run with -update to re-record all limits.
"""

import argparse
import math
import os
import re
import subprocess
import sys

INIT_LINE = re.compile(r"^init (\S+) @\S+ ms, (\S+) ms clock")

# 2x is exceeded by load spikes when the file was recorded on a machine ~1.3x faster than
# CI; 3x was not exceeded in any measurement, and 4x leaves margin for slower runners.
TOLERANCE = 4

# Limit for packages not in the golden file. Most inits report under 0.01 ms, where
# relative noise is meaningless and the cost is immaterial.
MIN_LIMIT_MS = 0.1


def header(max_ms):
    return f"""\
# Init time BUDGET per Go package, in ms of init() clock time (GODEBUG=inittrace=1),
# measured as the minimum over several runs of `databricks --version` on linux/amd64.
#
# Each budget is initialized at {TOLERANCE}x the package's measured minimum, for headroom.
# The smallest budget is {MIN_LIMIT_MS} ms; packages not listed here have a budget of {MIN_LIMIT_MS} ms.
# A package that exceeds its budget gets a new budget of {TOLERANCE}x its new minimum: the test
# fails on the diff, which you accept with -update after review. Budgets never shrink;
# delete this file and run with -update to re-measure all of them.
#
# Independently, the test fails if any package takes over {max_ms:g} ms; -update cannot raise that.
# Generated by acceptance/bin/check_init_time.py.
"""


def is_recorded(pkg):
    # Names and set of FIPS module packages depend on GOFIPS140, which differs between
    # `task test` and plain `go test`.
    return not pkg.startswith("crypto/internal/fips140")


def measure(command):
    # Some inits search PATH (github.com/atotto/clipboard looks up clipboard tools), so their
    # time depends on the machine's PATH; a fixed PATH keeps the budgets comparable.
    env = dict(os.environ, GODEBUG="inittrace=1", PATH=os.defpath)
    cp = subprocess.run(command, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
    if cp.returncode != 0:
        sys.exit(f"command failed with exit code {cp.returncode}:\n{cp.stderr}")
    clocks = {m.group(1): float(m.group(2)) for m in map(INIT_LINE.match, cp.stderr.splitlines()) if m}
    if not clocks:
        sys.exit(f"no inittrace output from {command}:\n{cp.stderr}")
    return clocks


def read_limits(path):
    limits = {}
    if os.path.exists(path):
        with open(path) as f:
            for line in f:
                if line.strip() and not line.startswith("#"):
                    limit, pkg = line.split()
                    limits[pkg] = float(limit)
    return limits


def format_limit(ms):
    # Aligned on the decimal point so cheap and expensive packages are easy to tell apart.
    whole, frac = (f"{ms:.1f}" if ms >= 1 else f"{ms:.2f}").split(".")
    return f"{whole:>3}.{frac:<2}"


def new_limit(ms):
    # Round up to two significant digits so the limit is never below TOLERANCE * ms.
    limit = TOLERANCE * ms
    scale = 10 if limit >= 1 else 100
    return math.ceil(limit * scale) / scale


def over_limit(runs, limits):
    pkgs = filter(is_recorded, runs[0])
    return [p for p in pkgs if min(r[p] for r in runs) > limits.get(p, MIN_LIMIT_MS)]


def find_failures(runs, max_ms):
    failures = []
    for pkg in runs[0]:
        clocks = [r[pkg] for r in runs]
        if min(clocks) > max_ms:
            failures.append(
                f"init of {pkg} took {min(clocks):.2f} ms (min) / {max(clocks):.2f} ms (max) "
                f"over {len(runs)} runs; threshold is {max_ms} ms"
            )
    return failures


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", type=int, default=5)
    parser.add_argument("--max-runs", type=int, default=20)
    parser.add_argument("--max-ms", type=float, required=True)
    parser.add_argument("--limits", required=True, help="golden file name, read from $TESTDIR and written to cwd")
    parser.add_argument("command", nargs="+")
    args = parser.parse_args()

    limits_path = os.path.join(os.environ["TESTDIR"], args.limits)
    # When recording from scratch, list every package whose limit exceeds MIN_LIMIT_MS so
    # each gets TOLERANCE headroom. Afterwards only exceeded limits are added, so packages
    # measuring near MIN_LIMIT_MS / TOLERANCE don't flip in and out of the file.
    record_all = not os.path.exists(limits_path)
    limits = read_limits(limits_path)

    runs = [measure(args.command) for _ in range(args.runs)]
    while len(runs) < args.max_runs and (find_failures(runs, args.max_ms) or over_limit(runs, limits)):
        runs.append(measure(args.command))

    exceeded = set(over_limit(runs, limits))
    with open(args.limits, "w") as f:
        f.write(header(args.max_ms))
        for pkg in sorted(filter(is_recorded, runs[0])):
            limit = limits.get(pkg)
            if pkg in exceeded or (record_all and limit is None):
                limit = new_limit(min(r[pkg] for r in runs))
                limit = limit if limit > MIN_LIMIT_MS else None
            if limit is not None:
                f.write(f"{format_limit(limit)} {pkg}\n")

    failures = find_failures(runs, args.max_ms)
    if not failures:
        print("OK: package init times are within threshold")
        return

    print("FAIL: Go package init() is slow; this adds latency to every CLI invocation.")
    for f in failures:
        print(f"  {f}")
    print("To investigate:")
    print("  GODEBUG=inittrace=1 databricks --version 2>&1 | sort -k5 -n -r | head")
    print("  go mod why -m <module>")
    sys.exit(1)


if __name__ == "__main__":
    main()
