// The scanned directories are relative to the repository root, three levels above
// this package.
var sharedCodeRoot = filepath.Join("..", "..", "..")

// sharedCodeDirs hold the bundle implementation.
var sharedCodeDirs = []string{"bundle", "cmd/bundle"}

// sharedCodeExclusions are paths under sharedCodeDirs that are not checked, with the reason.
var sharedCodeExclusions = map[string]string{
	"bundle/config/resources.go":           "config.Resources is the one hand-written list of resource types",
	"bundle/deploy/terraform":              "maps the resource types that state of the removed Terraform engine can hold, a fixed set",
	"bundle/terraform_dabs_map":            "maps the fields of the resource types that state of the removed Terraform engine can hold, a fixed set",
	"bundle/internal/validation/generated": "generated by ./task generate-validation",
}

const (
	sharedCodeTestName     = "TestSharedCodeNamesNoNewResourceTypes"
	sharedCodeResourcesPkg = "github.com/databricks/cli/bundle/config/resources"
)

var sharedCodeRecordPath = filepath.Join("testdata", "shared_code_resource_types.txt")

// sharedCodeRecordName is the record's path from the repository root, for messages.
const sharedCodeRecordName = "bundle/config/resources/testdata/shared_code_resource_types.txt"

const sharedCodeRecordHeader = `# Shared files of the bundle implementation that name resource types, and the keys of
# the types each one names. TestSharedCodeNamesNoNewResourceTypes fails when a file names
# a type that is not listed here, and when a listed type is no longer named.
# Regenerate with: go test ./bundle/config/resources -run TestSharedCodeNamesNoNewResourceTypes -update
`

// TestSharedCodeNamesNoNewResourceTypes keeps shared code from naming resource types
// beyond what the record lists. Shared code is every hand-written, non-test Go file under
// sharedCodeDirs except per-type files, which are named after a resource key
// (<key>.go or <key>_<aspect>.go). A file names a resource type if it contains:
//
//   - a string literal that is a resource key ("jobs"), or that holds a resource key
//     after "resources." ("resources.jobs.%s");
//   - a field of config.Resources, selected from an expression ending in Resources
//     (b.Config.Resources.Jobs) or set in a Resources{...} literal;
//   - a config type of a resource type (resources.Job, or Job inside package resources).
//
// Comments do not count. References through other names (a variable holding
// config.Resources, an SDK type, a singular name such as "job") are not detected.
func TestSharedCodeNamesNoNewResourceTypes(t *testing.T) {
	found := scanSharedCode(t)

	if testdiff.OverwriteMode {
		require.NoError(t, os.WriteFile(sharedCodeRecordPath, []byte(formatSharedCodeRecord(found)), 0o644))
		return
	}

	data, err := os.ReadFile(sharedCodeRecordPath)
	require.NoError(t, err)
	record := testdiff.NormalizeNewlines(string(data))
	recorded := parseSharedCodeRecord(t, record)
	for _, file := range slices.Sorted(maps.Keys(found)) {
		for _, key := range slices.Sorted(maps.Keys(found[file])) {
			if recorded[file][key] {
				continue
			}
			t.Errorf("%s names resource type %q (%s), which %s does not list for this file.\n"+
				"Shared code must not name resource types: put logic about one type in a file of that type, "+
				"as \"Adding a resource type\" in bundle/config/resources/README.md describes. "+
				"A file about one type is named after its key (%s.go or %s_<aspect>.go). "+
				"If this shared file must name the type, add it to the record with "+
				"`go test ./bundle/config/resources -run %s -update` and say why in the pull request.",
				file, key, found[file][key], sharedCodeRecordName, key, key, sharedCodeTestName)
		}
	}
	for _, file := range slices.Sorted(maps.Keys(recorded)) {
		for _, key := range slices.Sorted(maps.Keys(recorded[file])) {
			if _, ok := found[file][key]; ok {
				continue
			}
			t.Errorf("%s no longer names resource type %q. Remove it from the record %s with "+
				"`go test ./bundle/config/resources -run %s -update`.",
				file, key, sharedCodeRecordName, sharedCodeTestName)
		}
	}

	// A sorted record keeps each change to it a one-line diff.
	if !t.Failed() {
		assert.Equal(t, formatSharedCodeRecord(found), record, "%s is not in its canonical form; regenerate it with "+
			"`go test ./bundle/config/resources -run %s -update`", sharedCodeRecordName, sharedCodeTestName)
	}
}

// resourceTypeNames holds what identifies a resource type in source code, each mapped
// to the type's key.
type resourceTypeNames struct {
	keys   map[string]bool
	fields map[string]string
	types  map[string]string
}

func newResourceTypeNames() resourceTypeNames {
	n := resourceTypeNames{keys: map[string]bool{}, fields: map[string]string{}, types: map[string]string{}}
	byType := map[reflect.Type]string{}
	for _, rt := range config.AllResourceTypes() {
		n.keys[rt.Key] = true
		n.types[rt.Type.Name()] = rt.Key
		byType[rt.Type] = rt.Key
	}
	for _, f := range reflect.VisibleFields(reflect.TypeFor[config.Resources]()) {
		n.fields[f.Name] = byType[f.Type.Elem().Elem()]
	}
	return n
}

// perTypeKey returns the resource key a file is named after.
func (n resourceTypeNames) perTypeKey(file string) (string, bool) {
	stem := strings.TrimSuffix(filepath.Base(file), ".go")
	for key := range n.keys {
		if stem == key || strings.HasPrefix(stem, key+"_") {
			return key, true
		}
	}
	return "", false
}

// keysInString returns the resource keys a string literal names.
func (n resourceTypeNames) keysInString(s string) []string {
	if n.keys[s] {
		return []string{s}
	}
	var keys []string
	segments := strings.Split(s, ".")
	for i := 1; i < len(segments); i++ {
		if n.keys[segments[i]] && strings.HasSuffix(segments[i-1], "resources") {
			keys = append(keys, segments[i])
		}
	}
	return keys
}

func isSharedCodeExcluded(file string) bool {
	for path := range sharedCodeExclusions {
		if file == path || strings.HasPrefix(file, path+"/") {
			return true
		}
	}
	return false
}

// scanSharedCode returns, for every shared file that names a resource type, the keys
// of the types it names, each with a description of its first occurrence. Files are
// keyed by their path from the repository root, with forward slashes.
func scanSharedCode(t *testing.T) map[string]map[string]string {
	names := newResourceTypeNames()
	found := map[string]map[string]string{}

	for _, dir := range sharedCodeDirs {
		err := filepath.WalkDir(filepath.Join(sharedCodeRoot, filepath.FromSlash(dir)), func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				if d.Name() == "testdata" {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			rel, err := filepath.Rel(sharedCodeRoot, path)
			if err != nil {
				return err
			}
			file := filepath.ToSlash(rel)
			if isSharedCodeExcluded(file) {
				return nil
			}
			if _, ok := names.perTypeKey(file); ok {
				return nil
			}

			fset := token.NewFileSet()
			f, err := parser.ParseFile(fset, path, nil, parser.ParseComments|parser.SkipObjectResolution)
			if err != nil {
				return err
			}
			if ast.IsGenerated(f) {
				return nil
			}
			for key, occurrence := range resourceTypesNamedIn(f, fset, names, strings.HasPrefix(file, "bundle/config/resources/")) {
				if found[file] == nil {
					found[file] = map[string]string{}
				}
				found[file][key] = occurrence
			}
			return nil
		})
		require.NoError(t, err)
	}
	return found
}

// resourceTypesNamedIn returns the keys of the resource types f names, each with a
// description of its first occurrence. inResourcesPackage is set for files of package
// resources, which refer to config types without a package name.
func resourceTypesNamedIn(f *ast.File, fset *token.FileSet, names resourceTypeNames, inResourcesPackage bool) map[string]string {
	type occurrence struct {
		pos  token.Pos
		what string
	}
	first := map[string]occurrence{}
	add := func(key string, pos token.Pos, what string) {
		if o, ok := first[key]; !ok || pos < o.pos {
			first[key] = occurrence{pos, what}
		}
	}

	resourcesPkgNames := map[string]bool{}
	for _, imp := range f.Imports {
		if path, _ := strconv.Unquote(imp.Path.Value); path == sharedCodeResourcesPkg {
			name := "resources"
			if imp.Name != nil {
				name = imp.Name.Name
			}
			resourcesPkgNames[name] = true
		}
	}

	// Identifiers that are not references to a type: selected names, field and
	// function names, and keys of composite literals.
	notReferences := map[*ast.Ident]bool{}
	ast.Inspect(f, func(node ast.Node) bool {
		switch node := node.(type) {
		case *ast.ImportSpec:
			return false
		case *ast.BasicLit:
			if node.Kind != token.STRING {
				return true
			}
			if s, err := strconv.Unquote(node.Value); err == nil {
				for _, key := range names.keysInString(s) {
					add(key, node.Pos(), "string "+node.Value)
				}
			}
		case *ast.SelectorExpr:
			notReferences[node.Sel] = true
			if key, ok := names.fields[node.Sel.Name]; ok && endsInResources(node.X) {
				add(key, node.Pos(), "field Resources."+node.Sel.Name)
			}
			if x, ok := node.X.(*ast.Ident); ok && resourcesPkgNames[x.Name] {
				if key, ok := names.types[node.Sel.Name]; ok {
					add(key, node.Pos(), "type "+x.Name+"."+node.Sel.Name)
				}
			}
		case *ast.CompositeLit:
			if !endsInResources(node.Type) {
				return true
			}
			for _, elt := range node.Elts {
				if kv, ok := elt.(*ast.KeyValueExpr); ok {
					if id, ok := kv.Key.(*ast.Ident); ok {
						if key, ok := names.fields[id.Name]; ok {
							add(key, id.Pos(), "field Resources."+id.Name)
						}
					}
				}
			}
		case *ast.KeyValueExpr:
			if id, ok := node.Key.(*ast.Ident); ok {
				notReferences[id] = true
			}
		case *ast.Field:
			for _, id := range node.Names {
				notReferences[id] = true
			}
		case *ast.FuncDecl:
			notReferences[node.Name] = true
		case *ast.Ident:
			if inResourcesPackage && !notReferences[node] {
				if key, ok := names.types[node.Name]; ok {
					add(key, node.Pos(), "type "+node.Name)
				}
			}
		}
		return true
	})

	result := map[string]string{}
	for key, o := range first {
		result[key] = fmt.Sprintf("%s at line %d", o.what, fset.Position(o.pos).Line)
	}
	return result
}

// endsInResources reports whether expr is the identifier Resources or a selection of it,
// as in b.Config.Resources or config.Resources.
func endsInResources(expr ast.Expr) bool {
	switch expr := expr.(type) {
	case *ast.Ident:
		return expr.Name == "Resources"
	case *ast.SelectorExpr:
		return expr.Sel.Name == "Resources"
	}
	return false
}

func formatSharedCodeRecord(found map[string]map[string]string) string {
	var b strings.Builder
	b.WriteString(sharedCodeRecordHeader)
	for _, file := range slices.Sorted(maps.Keys(found)) {
		fmt.Fprintf(&b, "%s: %s\n", file, strings.Join(slices.Sorted(maps.Keys(found[file])), " "))
	}
	return b.String()
}

func parseSharedCodeRecord(t *testing.T, record string) map[string]map[string]bool {
	recorded := map[string]map[string]bool{}
	for line := range strings.Lines(record) {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		file, keys, ok := strings.Cut(line, ": ")
		require.Truef(t, ok, "%s: malformed line %q", sharedCodeRecordName, line)
		recorded[file] = map[string]bool{}
		for key := range strings.FieldsSeq(keys) {
			recorded[file][key] = true
		}
	}
	return recorded
}
