package walk

import (
	"maps"
	"reflect"
	"slices"
	"strings"

	"github.com/databricks/cli/bundle/config"
	"github.com/databricks/cli/libs/structs/structvar"
)

// Mode selects the strings [Strings] visits.
type Mode int

const (
	// WithReferences visits the strings that contain a variable reference ("${").
	WithReferences Mode = iota
)

// StringFunc is called for a visited string s at n. It returns a replacement and
// whether to store it.
type StringFunc func(n *Node, s string) (string, bool)

// Strings calls fn for the strings of the configuration selected by mode, with plain
// field access (strings_walk.go is generated by bundle/internal/validation). Pure
// references in fields that cannot hold a string are not strings: see
// [config.Root.References].
//
// TODO: processors that run back to back (e.g. reference collection and the
// workspace-prefix rewrite) could share one walk: visit every string with its kind
// (empty, plain, containing "${", pure reference) and dispatch to each processor,
// paying for the traversal once. Phase ordering limits which ones can be combined.
func Strings(root *config.Root, mode Mode, fn StringFunc) {
	c := &stringsWalk{mode: mode, fn: fn}
	n := Root(root)
	stringsConfigRoot(c, &n, root)
}

type stringsWalk struct {
	mode Mode
	fn   StringFunc
}

func (c *stringsWalk) match(s string) bool {
	return strings.Contains(s, "${")
}

// any visits the strings of a dynamic value (e.g. a variable value): the maps, slices
// and strings that decoding produces.
func (c *stringsWalk) any(n *Node, v *any) {
	switch x := (*v).(type) {
	case string:
		if c.match(x) {
			if r, ok := c.fn(n, x); ok {
				*v = r
			}
		}
	case map[string]any:
		for _, k := range sortedKeys(x) {
			e := x[k]
			ch := n.Child(k)
			c.any(&ch, &e)
			x[k] = e
		}
	case []any:
		for i := range x {
			ch := n.Elem(i)
			c.any(&ch, &x[i])
		}
	case nil:
	default:
		// Other values set from code (typed maps, slices, structs, named strings).
		rv := reflect.ValueOf(v).Elem()
		c.value(n, rv)
	}
}

// value visits the strings of the dynamic value v, which is settable.
func (c *stringsWalk) value(n *Node, v reflect.Value) {
	switch v.Kind() {
	case reflect.Interface, reflect.Pointer:
		if v.IsNil() {
			return
		}
		e := v.Elem()
		if v.Kind() == reflect.Interface {
			// Interface values are not settable: visit a copy and store it back.
			cp := reflect.New(e.Type()).Elem()
			cp.Set(e)
			c.value(n, cp)
			v.Set(cp)
			return
		}
		c.value(n, e)
	case reflect.String:
		if s := v.String(); c.match(s) {
			if r, ok := c.fn(n, s); ok {
				v.SetString(r)
			}
		}
	case reflect.Slice, reflect.Array:
		for i := range v.Len() {
			ch := n.Elem(i)
			c.value(&ch, v.Index(i))
		}
	case reflect.Map:
		if v.Type().Key().Kind() != reflect.String {
			return
		}
		keys := v.MapKeys()
		slices.SortFunc(keys, func(a, b reflect.Value) int { return strings.Compare(a.String(), b.String()) })
		for _, k := range keys {
			e := reflect.New(v.Type().Elem()).Elem()
			e.Set(v.MapIndex(k))
			ch := n.Child(k.String())
			c.value(&ch, e)
			v.SetMapIndex(k, e)
		}
	case reflect.Struct:
		info := structvar.GetStructInfo(v.Type())
		for _, f := range info.List {
			ch := n.Child(f.Key)
			c.value(&ch, structvar.FieldByIndex(v, f.Index))
		}
	default:
	}
}

// sortedKeys returns the keys of m in the order maps are visited.
func sortedKeys[K ~string, V any](m map[K]V) []K {
	return slices.Sorted(maps.Keys(m))
}
