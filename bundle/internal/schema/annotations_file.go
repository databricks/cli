// fieldsKey nests a type's block of field nodes inside the node of a field
// that resolves to it.
//
// typeDocKey holds the documentation for the type a field's value resolves to
// (for map and sequence fields: each entry). It is applied to the type's
// shared $defs entry, so it shows up at every occurrence of the type; this is
// also where enum values live.
//
// Both are "$"-prefixed so they cannot be mistaken for — or collide with — a
// config field of the same name (e.g. artifacts.*.type), which always appears
// as a bare key inside "$fields".
const (
	fieldsKey  = "$fields"
	typeDocKey = "$type"
)

// lineTypeDoc and lineFields sort the "$type" and "$fields" keys after a
// node's inline descriptor keys, which the saver orders with small line
// numbers (see descriptorKeyOrder).
const (
	lineTypeDoc = 9999
	lineFields  = 10000
)

// Layout of the annotations directory. Every file is a slice of one tree:
// root.yml holds the top-level config keys, and each resource type under
// "resources" gets its own file (jobs.yml, pipelines.yml, ...) holding that
// resource's node. Three layers share this slicing, told apart by a suffix
// before the extension: hand-written docs for CLI-only fields (no suffix),
// hand-written entries for fields cli.json already defines (".overrides"),
// and the generated list of undocumented fields (".generated").
const (
	resourcesKey    = "resources"
	rootFileName    = "root"
	handSuffix      = ""
	overridesSuffix = ".overrides"
	generatedSuffix = ".generated"
	yamlExt         = ".yml"
)

// layerHeaders is the comment block written above each file of a layer.
var layerHeaders = map[string]string{
	handSuffix:      annotationsFileHeader,
	overridesSuffix: overridesFileHeader,
	generatedSuffix: generatedFileHeader,
}

const annotationsFileHeader = `# Hand-written documentation the CLI owns for the bundle configuration JSON
# schema. See README.md in this directory for the format. "task generate-schema"
# normalizes this file and drops entries for fields that no longer exist; it
# never adds content here.
`

const overridesFileHeader = `# Hand-written documentation for fields that the upstream API spec
# (.codegen/cli.json) already defines: description overrides, gap fills for
# undocumented upstream fields, and deprecations the spec does not carry. Every
# entry here is a candidate to move upstream (fix the proto / OpenAPI docs) and
# then delete. "task generate-schema" routes entries between the .overrides
# files and the other hand-written files by whether the field exists upstream,
# so an entry added elsewhere lands here on the next run.
`

const generatedFileHeader = `# GENERATED by "task generate-schema". DO NOT EDIT.
# Fields that have no documentation in .codegen/cli.json or in the hand-written
# files of this directory. To document one, add it to the matching hand-written
# file at the same tree position and regenerate. See README.md.
`

// descriptorKeys is the set of YAML keys a node carries inline (the JSON tags
// of annotation.Descriptor).
var descriptorKeys = func() map[string]bool {
	keys := map[string]bool{}
	for field := range reflect.TypeFor[annotation.Descriptor]().Fields() {
		keys[strings.Split(field.Tag.Get("json"), ",")[0]] = true
	}
	return keys
}()

// descriptorKeyOrder is the leading key order for a serialized descriptor,
// matching the formatting of the previous annotation files. Remaining keys
// follow alphabetically.
var descriptorKeyOrder = []string{"description", "markdown_description", "title", "default", "enum"}

// descriptorToMap serializes d into dst with its keys ordered. It returns the
// nil value (writing nothing) when d carries no content.
//
// The empty check relies on the dyn.NilValue reference: with a nil reference,
// FromTyped omits zero-valued fields, so an all-zero descriptor collapses to
// KindNil rather than an empty map. Do not pass a map reference here, or empty
// descriptors would start serializing as "{}".
func descriptorToMap(d annotation.Descriptor, dst map[string]dyn.Value) (dyn.Value, error) {
	v, err := convert.FromTyped(d, dyn.NilValue)
	if err != nil || v.Kind() == dyn.KindNil {
		return dyn.NilValue, err
	}
	return yamlsaver.ConvertToMapValue(d, yamlsaver.NewOrder(descriptorKeyOrder), []string{}, dst)
}

// descriptorEmpty reports whether d carries no documentation. See
// descriptorToMap for why the nil reference is what makes this work.
func descriptorEmpty(d annotation.Descriptor) bool {
	v, err := convert.FromTyped(d, dyn.NilValue)
	return err == nil && v.Kind() == dyn.KindNil
}

// loadAnnotationsDir reads one layer of the annotations directory, selected by
// its file-name suffix, and flattens it into per-type annotations. root.yml is
// loaded as the root block; every other file is the node of the resource type
// it is named after. Tree positions that do not resolve to a type or field in
// the config (stale entries, typos, a file for a resource that no longer
// exists) are returned in unknown; they are not loaded, so the next save drops
// them.
func loadAnnotationsDir(dir, suffix string, g *typeGraph) (annotation.File, []string, error) {
	names, err := listLayer(dir, suffix)
	if err != nil {
		return nil, nil, err
	}
	resources, _ := g.edge(g.root, resourcesKey)

	l := &fileLoader{graph: g, data: annotation.File{}}
	for _, name := range names {
		path := filepath.Join(dir, layerFileName(name, suffix))
		b, err := os.ReadFile(path)
		if err != nil {
			return nil, nil, err
		}
		v, err := yamlloader.LoadYAML(path, bytes.NewBuffer(b))
		if err != nil {
			return nil, nil, err
		}

		if name == rootFileName {
			err = l.block(v, g.root, "")
		} else if edge, ok := g.edge(resources.typ, name); ok {
			err = l.node(v, resources.typ, edge, resourcesKey+"."+fieldsKey+"."+name)
		} else {
			l.unknown = append(l.unknown, filepath.Base(path))
		}
		if err != nil {
			return nil, nil, err
		}
	}
	return l.data, l.unknown, nil
}

// layerFileName returns the file name for a slice of one layer.
func layerFileName(name, suffix string) string {
	return name + suffix + yamlExt
}

// listLayer returns the slice names of one layer present in dir, sorted.
func listLayer(dir, suffix string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		name, ok := strings.CutSuffix(e.Name(), yamlExt)
		if !ok {
			continue
		}
		if layerSuffix(name) != suffix {
			continue
		}
		names = append(names, strings.TrimSuffix(name, suffix))
	}
	return names, nil
}

// layerSuffix returns the layer suffix of a file name without its extension.
func layerSuffix(name string) string {
	for _, suffix := range []string{overridesSuffix, generatedSuffix} {
		if strings.HasSuffix(name, suffix) {
			return suffix
		}
	}
	return handSuffix
}

type fileLoader struct {
	graph   *typeGraph
	data    annotation.File
	unknown []string
}

// block loads one type's block of field nodes.
func (l *fileLoader) block(v dyn.Value, typeKey, where string) error {
	if v.Kind() == dyn.KindNil {
		return nil
	}
	m, ok := v.AsMap()
	if !ok {
		return fmt.Errorf("%s: expected a mapping, got %s", where, v.Kind())
	}

	for _, pair := range m.Pairs() {
		key := pair.Key.MustString()
		child := where + "." + key
		if where == "" {
			child = key
		}

		edge, ok := l.graph.edge(typeKey, key)
		if !ok {
			l.unknown = append(l.unknown, child)
			continue
		}
		err := l.node(pair.Value, typeKey, edge, child)
		if err != nil {
			return err
		}
	}
	return nil
}

// node loads one field's node: the inline descriptor for the field, the
// "$type" docs for the type it resolves to, and the "$fields" block of that
// type's fields.
func (l *fileLoader) node(v dyn.Value, typeKey string, edge fieldEdge, where string) error {
	if v.Kind() == dyn.KindNil {
		return nil
	}
	m, ok := v.AsMap()
	if !ok {
		return fmt.Errorf("%s: expected a mapping, got %s", where, v.Kind())
	}

	desc := dyn.NewMapping()
	for _, pair := range m.Pairs() {
		key := pair.Key.MustString()
		switch {
		case key == fieldsKey && edge.typ != "":
			err := l.block(pair.Value, edge.typ, where+"."+fieldsKey)
			if err != nil {
				return err
			}
		case key == typeDocKey && edge.typ != "":
			d, ok, err := l.descriptor(pair.Value, where+"."+typeDocKey)
			if err != nil {
				return err
			}
			if ok {
				l.data.SetSelf(edge.typ, d)
			}
		case descriptorKeys[key]:
			desc.SetLoc(key, nil, pair.Value)
		default:
			l.unknown = append(l.unknown, where+"."+key)
		}
	}

	if desc.Len() > 0 {
		d, err := toDescriptor(desc, where)
		if err != nil {
			return err
		}
		l.data.SetField(typeKey, edge.name, d)
	}
	return nil
}

// descriptor parses a mapping of descriptor keys (the value of a "$type" key).
// Non-descriptor keys are flagged as unknown. The second return is false when
// the mapping carries no descriptor keys.
func (l *fileLoader) descriptor(v dyn.Value, where string) (annotation.Descriptor, bool, error) {
	m, ok := v.AsMap()
	if !ok {
		return annotation.Descriptor{}, false, fmt.Errorf("%s: expected a mapping, got %s", where, v.Kind())
	}
	desc := dyn.NewMapping()
	for _, pair := range m.Pairs() {
		key := pair.Key.MustString()
		if descriptorKeys[key] {
			desc.SetLoc(key, nil, pair.Value)
		} else {
			l.unknown = append(l.unknown, where+"."+key)
		}
	}
	if desc.Len() == 0 {
		return annotation.Descriptor{}, false, nil
	}
	d, err := toDescriptor(desc, where)
	return d, err == nil, err
}

// toDescriptor converts a mapping of descriptor keys to a typed descriptor.
func toDescriptor(desc dyn.Mapping, where string) (annotation.Descriptor, error) {
	var d annotation.Descriptor
	err := convert.ToTyped(&d, dyn.V(desc))
	if err != nil {
		return annotation.Descriptor{}, fmt.Errorf("%s: %w", where, err)
	}
	return d, nil
}

// saveAnnotationsDir writes data as one layer of the annotations directory,
// selected by its file-name suffix, in the canonical tree layout: a depth-first
// walk over the config type graph in struct declaration order expands every
// type at its first occurrence; keys are emitted alphabetically. The tree is
// sliced into root.yml plus one file per resource type. Slices without content
// are not written, and files of the layer that were not written are removed.
// Entries that no tree position consumed (fields or types that no longer
// exist) are returned as detached and are not written.
func saveAnnotationsDir(dir, suffix string, data annotation.File, g *typeGraph) ([]string, error) {
	root, detached, err := renderTree(data, g)
	if err != nil {
		return nil, err
	}

	err = os.MkdirAll(dir, 0o755)
	if err != nil {
		return nil, err
	}
	written := map[string]bool{}
	for name, content := range splitResources(root) {
		if len(content) == 0 {
			continue
		}
		err = writeSlice(filepath.Join(dir, layerFileName(name, suffix)), layerHeaders[suffix], content)
		if err != nil {
			return nil, err
		}
		written[name] = true
	}

	// A slice that lost all its content (a resource that was removed, or whose
	// fields are all documented now) must not linger as a stale file.
	existing, err := listLayer(dir, suffix)
	if err != nil {
		return nil, err
	}
	for _, name := range existing {
		if written[name] {
			continue
		}
		err = os.Remove(filepath.Join(dir, layerFileName(name, suffix)))
		if err != nil {
			return nil, err
		}
	}
	return detached, nil
}

// renderTree renders data as the root block of the canonical tree and returns
// the entries no tree position consumed.
func renderTree(data annotation.File, g *typeGraph) (map[string]dyn.Value, []string, error) {
	s := &fileSaver{
		graph:        g,
		data:         data,
		visited:      map[string]bool{g.root: true},
		expandAt:     map[edgeKey]bool{},
		consumed:     map[edgeKey]bool{},
		selfConsumed: map[string]bool{},
	}
	s.assignCanonical(g.root)

	root, err := s.block(g.root)
	if err != nil {
		return nil, nil, err
	}
	return root, s.detached(), nil
}

// splitResources slices the rendered root block into per-file contents: the
// node of each resource type under "resources" becomes its own slice, named
// after the resource; everything else (including the "resources" node's own
// descriptor) stays in the root slice.
func splitResources(root map[string]dyn.Value) map[string]map[string]dyn.Value {
	files := map[string]map[string]dyn.Value{rootFileName: root}
	res, ok := root[resourcesKey]
	if !ok {
		return files
	}
	resNode := map[string]dyn.Value{}
	for _, pair := range res.MustMap().Pairs() {
		key := pair.Key.MustString()
		if key != fieldsKey {
			resNode[key] = pair.Value
			continue
		}
		for _, r := range pair.Value.MustMap().Pairs() {
			node := map[string]dyn.Value{}
			for _, p := range r.Value.MustMap().Pairs() {
				node[p.Key.MustString()] = p.Value
			}
			files[r.Key.MustString()] = node
		}
	}
	if len(resNode) == 0 {
		delete(root, resourcesKey)
	} else {
		root[resourcesKey] = dyn.NewValue(resNode, res.Locations())
	}
	return files
}

// writeSlice writes one file of a layer: the header comment followed by the
// content, with every top-level key styled so nested scalars render in literal
// block style.
func writeSlice(path, header string, content map[string]dyn.Value) error {
	style := map[string]yaml3.Style{}
	for k := range content {
		style[k] = yaml3.LiteralStyle
	}
	err := yamlsaver.NewSaverWithStyle(style).SaveAsYAML(content, path, true)
	if err != nil {
		return err
	}
	return prependCommentToFile(path, header)
}

type edgeKey struct {
	typ  string
	name string
}

type fileSaver struct {
	graph        *typeGraph
	data         annotation.File
	visited      map[string]bool
	expandAt     map[edgeKey]bool
	consumed     map[edgeKey]bool
	selfConsumed map[string]bool
}

// assignCanonical walks the type graph depth-first in struct declaration
// order and records, for every type, the field edge at which it is expanded.
func (s *fileSaver) assignCanonical(typeKey string) {
	for _, edge := range s.graph.fields[typeKey] {
		if edge.typ == "" || s.visited[edge.typ] {
			continue
		}
		s.visited[edge.typ] = true
		s.expandAt[edgeKey{typeKey, edge.name}] = true
		s.assignCanonical(edge.typ)
	}
}

// block renders one type's block of field nodes, emitted alphabetically.
// Lines in the value locations encode the output order for the YAML saver.
func (s *fileSaver) block(typeKey string) (map[string]dyn.Value, error) {
	out := map[string]dyn.Value{}
	line := 0

	edges := slices.Clone(s.graph.fields[typeKey])
	slices.SortFunc(edges, func(a, b fieldEdge) int {
		return strings.Compare(a.name, b.name)
	})
	for _, edge := range edges {
		node, err := s.node(typeKey, edge)
		if err != nil {
			return nil, err
		}
		if len(node) > 0 {
			out[edge.name] = dyn.NewValue(node, []diag.Location{{Line: line}})
			line++
		}
	}
	return out, nil
}

// node renders one field's node: the inline field descriptor plus, at the
// field's canonical position, the resolved type's "$type" docs and the
// "fields" block of its fields.
func (s *fileSaver) node(typeKey string, edge fieldEdge) (map[string]dyn.Value, error) {
	out := map[string]dyn.Value{}

	// The inline descriptor keys are written directly into the node, sharing
	// it with the "$type" and "$fields" keys added below.
	if d, ok := s.takeField(typeKey, edge.name); ok {
		if _, err := descriptorToMap(d, out); err != nil {
			return nil, err
		}
	}

	if s.expandAt[edgeKey{typeKey, edge.name}] {
		v, err := descriptorToMap(s.takeSelf(edge.typ), map[string]dyn.Value{})
		if err != nil {
			return nil, err
		}
		if v.Kind() != dyn.KindNil {
			out[typeDocKey] = v.WithLocations([]diag.Location{{Line: lineTypeDoc}})
		}

		child, err := s.block(edge.typ)
		if err != nil {
			return nil, err
		}
		if len(child) > 0 {
			out[fieldsKey] = dyn.NewValue(child, []diag.Location{{Line: lineFields}})
		}
	}
	return out, nil
}

// takeField returns the descriptor for a field and marks it consumed for the
// detached-entry report.
func (s *fileSaver) takeField(typeKey, name string) (annotation.Descriptor, bool) {
	d, ok := s.data[typeKey].Fields[name]
	if ok {
		s.consumed[edgeKey{typeKey, name}] = true
	}
	return d, ok
}

// takeSelf returns a type's own descriptor and marks it accounted for, whether
// or not it carries any docs (expanding the type is what consumes it).
func (s *fileSaver) takeSelf(typeKey string) annotation.Descriptor {
	s.selfConsumed[typeKey] = true
	return s.data[typeKey].Self
}

// detached returns the data entries no tree position consumed, sorted. These
// are fields or types that no longer exist in the config.
func (s *fileSaver) detached() []string {
	var out []string
	for typeKey, ta := range s.data {
		if !s.selfConsumed[typeKey] && !descriptorEmpty(ta.Self) {
			out = append(out, typeKey+": (type)")
		}
		for name := range ta.Fields {
			if !s.consumed[edgeKey{typeKey, name}] {
				out = append(out, typeKey+": "+name)
			}
		}
	}
	slices.Sort(out)
	return out
}

func prependCommentToFile(outputPath, comment string) error {
	b, err := os.ReadFile(outputPath)
	if err != nil {
		return err
	}
	f, err := os.OpenFile(outputPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()

	_, err = f.WriteString(comment)
	if err != nil {
		return err
	}
	_, err = f.Write(b)
	return err
}
