// TestConfigFiles guards the file naming the loader derives resource types from: a
// misspelled name would silently drop every rule in the file. A file holding no rules
// is a mistake too — an empty resource has no file at all.
func TestConfigFiles(t *testing.T) {
	names, err := fs.Glob(configFS, "*"+yamlSuffix)
	require.NoError(t, err)
	require.NotEmpty(t, names)

	for _, name := range names {
		resourceType := strings.TrimSuffix(strings.TrimSuffix(name, yamlSuffix), generatedSuffix)
		assert.Containsf(t, SupportedResources, resourceType, "%s: %q is not a supported resource type", name, resourceType)
	}

	for _, cfg := range []*Config{MustLoadConfig(), MustLoadGeneratedConfig()} {
		for resourceType, rc := range cfg.Resources {
			assert.NotEqualf(t, empty, rc, "%s: declares no rules; delete the file", resourceType)
		}
	}
}

